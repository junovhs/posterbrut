"""Recover a curated brush palette from the owner's vault (read-only).
Run with Python + Pillow: python scripts/import-tiptop-brushes.py /path/to/Vault
Outputs web-sized lossless assets, original archive metadata, and SHA-256 provenance.
"""
import hashlib, io, json, plistlib, re, sys, zipfile
from pathlib import Path
from PIL import Image
VAULT=Path(sys.argv[1]);ROOT=Path(__file__).resolve().parent.parent
SETS={
 '01_Inking_and_Comics/Master_Ink/Master_Ink_2022.brushset':['Low Ink','Flat Dry','Dry Ink Brush 1 1 1','Watery Brush','Dry Old Round','Bleeding Edge','Hake Wet','Fountain','Crisp Comic Pen'],
 '06_Textures_Patterns_FX/Spray_Paint/Real_Spray_Paint.brushset':['TTB_Spray_06','TTB_Spray_14','TTB_Spray_04','TTB_Drip_07'],
}
assets=ROOT/'assets/brushes';assets.mkdir(parents=True,exist_ok=True);presets=[];provenance=[]
def clamp(v,a,b):return max(a,min(b,v))
for relative,names in SETS.items():
 archive=VAULT/relative
 with zipfile.ZipFile(archive) as z:
  for member in z.namelist():
   if not member.endswith('Brush.archive') or '/Reset/' in member:continue
   decoded=plistlib.loads(z.read(member));objects=decoded['$objects'];a=objects[decoded['$top']['root'].data]
   def value(v):return objects[v.data] if isinstance(v,plistlib.UID) else v
   name=value(a.get('name'))
   if name not in names:continue
   id=re.sub('[^a-z0-9]+','-',name.lower()).strip('-');folder=member.rsplit('/',1)[0]
   preset={'id':id,'name':'Dry Ink Brush' if name=='Dry Ink Brush 1 1 1' else name.replace('TTB_Spray_','Spray ').replace('TTB_Drip_','Drip '),'set':'Master Ink' if 'Master_Ink' in relative else 'Real Spray Paint'}
   record={'id':id,'archive':relative,'member':member,'originalName':name,'archiveSha256':hashlib.sha256(archive.read_bytes()).hexdigest(),'assets':{}}
   for role in ['Shape','Grain']:
    source=folder+'/'+role+'.png'
    if source not in z.namelist():continue
    data=z.read(source);im=Image.open(io.BytesIO(data)).convert('RGBA');originalSize=im.size;im.thumbnail((512,512),Image.Resampling.LANCZOS);dest=assets/(id+'-'+role.lower()+'.webp');im.save(dest,lossless=True)
    preset[role.lower()]='assets/brushes/'+dest.name;record['assets'][role.lower()]={'member':source,'sourceSha256':hashlib.sha256(data).hexdigest(),'outputSha256':hashlib.sha256(dest.read_bytes()).hexdigest(),'originalSize':originalSize,'size':im.size}
   assert 'shape' in preset,name
   def curve(key):
    item=value(a.get(key));points=value(item.get('points')) if isinstance(item,dict) else None
    if not isinstance(points,dict):return [[0,0],[1,1]]
    return sorted([list(map(float,re.findall(r'-?\d+(?:\.\d+)?',value(p)))) for p in points.get('NS.objects',[])])
   preset.update(spacing=clamp(a.get('plotSpacing',.08),.04,1),scatter=clamp(a.get('shapeScatter',0),0,2),jitter=clamp(a.get('plotJitter',0),0,2),follow=abs(a.get('shapeRotation',0))>.1,angle=a.get('shapeAngle',0)*6.28318530718,pressureSize=clamp(a.get('dynamicsPressureSize',0),0,1),pressureOpacity=clamp(a.get('dynamicsPressureOpacity',0),0,1),minSize=clamp(a.get('minSize',.1)/max(.01,a.get('maxSize',1)),.05,1),minOpacity=clamp(a.get('minOpacity',0),0,1),sizeCurve=curve('dynamicsPressureSizeCurve'),opacityCurve=curve('dynamicsPressureOpacityCurve'),shapeInverted=a.get('shapeInverted',False),grainInverted=a.get('textureInverted',False),grainDepth=clamp(a.get('grainDepth',0),0,1))
   record['settings']={k:value(a[k]) for k in ['plotSpacing','shapeScatter','plotJitter','shapeRotation','shapeAngle','dynamicsPressureSize','dynamicsPressureOpacity','minSize','maxSize','minOpacity','grainDepth','shapeInverted','textureInverted'] if k in a};presets.append(preset);provenance.append(record)
order={name:i for i,name in enumerate([re.sub('[^a-z0-9]+','-',name.lower()).strip('-') for names in SETS.values() for name in names])};presets.sort(key=lambda b:order[b['id']])
assert len(presets)==sum(map(len,SETS.values()))
(ROOT/'src/threshold/brushes.ts').write_text('// Generated by scripts/import-tiptop-brushes.py from the owner’s vault.\nimport type {BrushPreset} from \'./types.js\';\nexport const brushPresets:readonly BrushPreset[]='+json.dumps(presets,indent=2)+';\n')
(assets/'provenance.json').write_text(json.dumps(provenance,indent=2)+'\n')
print(f'Recovered {len(presets)} original brush presets; {sum(p.stat().st_size for p in assets.glob("*.webp")):,} asset bytes.')
